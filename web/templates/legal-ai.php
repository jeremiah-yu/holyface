<section class="section">
  <div class="container prose legal">
    <p>Holy Face offers optional study helpers (study plan, flashcards, sample quizzes) inside the student app. This policy explains how they work and what they must never do.</p>
    <h2>Privacy first</h2>
    <p>Because many learners are minors, AMGS <strong>must not</strong> send a student’s name, LRN, photograph, guardian details, or contact information to any third-party AI provider. Generation runs on school-controlled servers from <em>class material text only</em>.</p>
    <h2>What is sent (and what is not)</h2>
    <ul>
      <li><strong>Allowed:</strong> subject notes and study-material content the School already uploaded.</li>
      <li><strong>Never allowed:</strong> name, LRN, photo, address, phone, email of a learner or parent as part of an AI prompt.</li>
    </ul>
    <h2>Accuracy and faith-centered use</h2>
    <p>AI output can be wrong. It is a study aid, not a teacher, not a counselor, and not an official grade. Learners remain responsible for original work and academic honesty. Content should stay consistent with the School’s Catholic identity and child-safeguarding rules.</p>
    <h2>Consent</h2>
    <p>Use of study tools may require recorded consent (learner and, where appropriate, parent/guardian). You may stop using the tools at any time; that does not delete encoded grades.</p>
    <h2>Human review</h2>
    <p>Teachers and the Registrar are not required to accept AI-generated quizzes as official assessments unless the School says so in writing.</p>
  </div>
</section>
